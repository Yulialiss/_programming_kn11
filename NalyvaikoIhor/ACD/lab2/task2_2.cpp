#include <iostream>
#include <ctime>
#include <cstdlib>

using namespace std;

int main() {
    const int N = 100; // Максимально можлива місткість масиву
    int arr[N];
    int n, A, B;

    // Введення початкової кількості елементів та діапазону значень
    cout << "Enter count (n <= 50): "; 
    cin >> n;
    cout << "Enter range (A B): ";
    cin >> A >> B;

    // Ініціалізація генератора випадкових чисел
    srand(time(0));
    cout << "Before: ";
    for (int i = 0; i < n; i++) {
        // Генерація чисел у діапазоні [A, B]
        arr[i] = A + rand() % (B - A + 1);
        cout << arr[i] << " ";
    }
    cout << endl;

    // Основний цикл обробки масиву
    for (int i = 0; i < n; i++) {
        // Перевірка, чи є поточне число парним
        if (arr[i] % 2 == 0) {
            // Перевірка, чи не вийдемо ми за межі масиву (N=100) при вставці
            if (n >= N) {
                cout << "\nLimit N=100 reached!" << endl;
                break;
            }

            // Зсув усіх елементів, що стоять після arr[i], на одну позицію вправо
            // Це звільняє місце для вставки квадрата числа
            for (int j = n; j > i + 1; j--) {
                arr[j] = arr[j - 1];
            }

            // Вставляємо квадрат парного числа на наступну позицію
            arr[i + 1] = arr[i] * arr[i];
            
            n++; // Збільшуємо фактичний розмір масиву
            i++; // Пропускаємо щойно вставлений квадрат, щоб не перевіряти його в наступній ітерації
        }
    }

    // Вивід зміненого масиву
    cout << "After:  ";
    for (int i = 0; i < n; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;

    return 0;
}

#include <iostream>
#include <ctime>
#include <cstdlib>

using namespace std;

int main() {
    const int n = 5; // Встановлюємо розмір квадратної матриці 5x5
    int A[n][n];

    srand(time(0)); // "Зерно" для випадкових чисел (щоб кожен запуск був унікальним)

    // Блок генерації та відображення матриці
    cout << "Matrix A:" << endl;
    for (int i = 0; i < n; i++) {       // Цикл по рядках
        for (int j = 0; j < n; j++) {   // Цикл по стовпцях
            // Генеруємо числа від -5 до 5
            A[i][j] = 5 - rand() % 11; 
            cout << A[i][j] << "\t";    // Виводимо через табуляцію
        }
        cout << endl; // Перехід на новий рядок після кожного рядка матриці
    }

    int rowIdx = -1;    // Сюди запишемо номер рядка знайденого нуля
    int colIdx = -1;    // Сюди запишемо номер стовпця знайденого нуля
    bool found = false; // Сигнальний прапорець: чи знайшли ми нуль

    // АЛГОРИТМ ПОШУКУ
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            if (A[i][j] == 0) { // Якщо поточний елемент — нуль
                rowIdx = i;     // Запам'ятовуємо рядок
                colIdx = j;     // Запам'ятовуємо стовпець
                found = true;   // Ставимо відмітку "знайдено"
                break;          // Виходимо з циклу стовпців
            }
        }
        if (found) break; // Якщо знайшли нуль, виходимо і з циклу рядків (щоб не шукати далі)
    }

    // Блок виведення результатів
    cout << "---------------------------" << endl;
    if (found) {
        // Якщо знайшли, показуємо координати (пам'ятай, індексація з 0)
        cout << "First zero element found!" << endl;
        cout << "Row: " << rowIdx << endl;
        cout << "Column: " << colIdx << endl;
        cout << "Coordinates: A[" << rowIdx << "][" << colIdx << "]" << endl;
    } else {
        // Якщо в усій матриці не було жодного нуля
        cout << "Zero element not found." << endl;
    }

    return 0;
}

#include <iostream> // Бібліотека для введення та виведення (cout, cin)
#include <iomanip>  // Бібліотека для форматування виводу (setprecision)

using namespace std;

int main() {
    int n; // Оголошення змінної для кількості ітерацій
    cout << "--- Zavdannya 2: Suma ryadiv ---" << endl;
    cout << "Vvedit naturalne chislo n: "; cin >> n; // Введення числа користувачем

    // Використовуємо double для S, щоб зберігати дуже великі числа, 
    // оскільки добутки в рядах швидко зростають і можуть переповнити int
    double S = 0; 
    
    // Зовнішній цикл - відповідає за підсумовування кожного окремого доданка рядка
    for (int i = 1; i <= n; i++) {
        double term_product = 1.0; // Змінна для обчислення добутку всередині поточного доданка
        
        // Внутрішній цикл - обчислює добуток послідовних чисел від i до 2i
        // Наприклад, якщо i=2, то перемножимо 2 * 3 * 4
        for (int j = i; j <= 2 * i; j++) {
            term_product *= j; // Накопичуємо результат множення
        }
        
        S += term_product; // Додаємо отриманий добуток до загальної суми S
    }

    // Виводимо результат. fixed та setprecision(0) прибирають наукову нотацію (e+) 
    // та дробову частину, щоб число виглядало як ціле
    cout << "Rezultat S = " << fixed << setprecision(0) << S << endl;

    return 0; // Повертаємо 0, що свідчить про успішне завершення програми
}
